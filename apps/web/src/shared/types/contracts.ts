export type ID = number;
export type ISODate = string;

export type AccountRole = 'STUDENT' | 'INSTRUCTOR' | 'ADMIN';
export type AccountStatus = 'ACTIVE' | 'LOCKED';
export type CohortStaffRole = 'INSTRUCTOR' | 'TA';
export type CourseStatus = 'DRAFT' | 'PUBLISHED' | 'ARCHIVED';
export type CohortStatus = 'DRAFT' | 'OPENING' | 'ONGOING' | 'COMPLETED' | 'ARCHIVED';
export type SessionStatus = 'SCHEDULED' | 'LIVE' | 'PROCESSING_REPLAY' | 'REPLAY_READY';
export type ActivityTag = 'THEORY' | 'EXERCISE_REVIEW' | 'LIVE_CODING' | 'WORKSHOP';
export type VideoProvider = 'R2_HLS_AES128' | 'YOUTUBE_PUBLIC' | 'BUNNY_STREAM';
export type OrderStatus = 'PENDING' | 'PAID' | 'FAILED' | 'EXPIRED' | 'CANCELED';
export type EnrollmentStatus = 'ACTIVE' | 'COMPLETED' | 'REVOKED';
export type AssessmentPurpose = 'SESSION_ASSIGNMENT' | 'FINAL_EXAM';
export type GradingMode = 'AUTO' | 'MANUAL' | 'HYBRID';
export type ItemType =
  | 'SINGLE_CHOICE'
  | 'MULTI_SELECT'
  | 'TRUE_FALSE'
  | 'SHORT_ANSWER'
  | 'ESSAY'
  | 'FILE_SUBMISSION';
export type AnswerGradingStatus = 'AUTO_GRADED' | 'PENDING_MANUAL' | 'MANUALLY_GRADED';
export type IntegrityVerdict = 'CLEAN' | 'FLAGGED' | 'CONFIRMED_CHEAT' | 'CLEARED_BY_INSTRUCTOR';
export type ChunkVisibility = 'PUBLIC' | 'ENROLLED_ONLY';
export type ChatScope = 'ADVISOR_GLOBAL' | 'SESSION_TUTOR' | 'LIVE_COPILOT';
export type SkillRelationRole = 'PREREQUISITE' | 'LEARNING_OUTCOME';

export interface Account {
  id: ID;
  email: string;
  role: AccountRole;
  status: AccountStatus;
  emailVerifiedAt: ISODate | null;
  hasPassword: boolean;
  googleLinked: boolean;
  profile: UserProfile;
  instructorProfile?: InstructorProfile;
}

export interface UserProfile {
  fullName: string;
  avatarUrl: string | null;
  bio: string | null;
  careerGoal: string | null;
  hasFaceReference: boolean;
}

export interface InstructorProfile {
  headline: string;
  organization: string | null;
  yearsOfExperience: number | null;
  expertiseSummaryMd: string | null;
  socialLinks: Record<string, string>;
}

export interface Category {
  id: ID;
  name: string;
  slug: string;
  parentId: ID | null;
}

export interface Skill {
  id: ID;
  code: string;
  name: string;
  categoryId: ID | null;
  description: string | null;
}

export interface CourseSkill {
  skill: Skill;
  role: SkillRelationRole;
  targetWeight: number;
}

export interface Course {
  id: ID;
  slug: string;
  title: string;
  shortDescription: string;
  descriptionMd: string;
  thumbnailUrl: string | null;
  previewYoutubeUrl: string | null;
  difficultyLevel: 1 | 2 | 3 | 4 | 5;
  category: Category;
  skills: CourseSkill[];
  syllabusTemplate: { order: number; title: string; activityTags: ActivityTag[] }[];
  status: CourseStatus;
  ratingAvg: number | null;
  reviewCount: number;
}

export interface CohortStaff {
  account: Pick<Account, 'id' | 'email'> & { profile: UserProfile; instructorProfile?: InstructorProfile };
  role: CohortStaffRole;
  scopeNote: string | null;
}

export interface Cohort {
  id: ID;
  courseId: ID;
  code: string;
  name: string;
  curriculumVersion: string;
  techStackNotes: string | null;
  tuitionVnd: number;
  enrolledCount: number;
  enrollmentOpenAt: ISODate;
  startDate: string;
  endDate: string;
  replayExpiresAt: ISODate | null;
  status: CohortStatus;
  staff: CohortStaff[];
}

export interface SessionAttachment {
  id: ID;
  fileName: string;
  mimeType: string;
  fileSizeBytes: number;
  uploadedBy: { id: ID; fullName: string };
  createdAt: ISODate;
}

export interface SessionSubtitle {
  id: ID;
  languageCode: string;
  isAutoGenerated: boolean;
  vttUrl: string;
}

export interface ClassSession {
  id: ID;
  cohortId: ID;
  sessionOrder: number;
  title: string;
  descriptionMd: string | null;
  activityTags: ActivityTag[];
  isFreePreview: boolean;
  host: { id: ID; fullName: string; avatarUrl: string | null };
  scheduledStart: ISODate | null;
  scheduledEnd: ISODate | null;
  status: SessionStatus;
  videoProvider: VideoProvider | null;
  durationSeconds: number | null;
  aiSummaryMd: string | null;
  attachments: SessionAttachment[];
  subtitles: SessionSubtitle[];
  lastUpdatedBy: { id: ID; fullName: string } | null;
  updatedAt: ISODate;
}

export interface PlaybackSession {
  manifestUrl: string;
  provider: VideoProvider;
  expiresAt: ISODate;
  watermark: { email: string; shortId: string };
}

export interface TranscriptSegment {
  startSec: number;
  endSec: number;
  text: string;
}

export interface Order {
  id: ID;
  orderCode: string;
  cohort: Pick<Cohort, 'id' | 'code' | 'name'>;
  courseTitle: string;
  amountVnd: number;
  status: OrderStatus;
  paidAt: ISODate | null;
  expiresAt: ISODate;
  createdAt: ISODate;
}

export interface Enrollment {
  id: ID;
  cohort: Cohort;
  course: Pick<Course, 'id' | 'slug' | 'title' | 'thumbnailUrl'>;
  status: EnrollmentStatus;
  finalExamPassed: boolean;
  enrolledAt: ISODate;
  completedAt: ISODate | null;
  progressPct: number;
  completedSessions: number;
  totalSessions: number;
}

export interface SessionProgress {
  sessionId: ID;
  lastPositionSec: number;
  isCompleted: boolean;
  completedAt: ISODate | null;
  lastActivityAt: ISODate;
}

export interface Assessment {
  id: ID;
  cohortId: ID;
  sessionId: ID | null;
  purpose: AssessmentPurpose;
  gradingMode: GradingMode;
  title: string;
  instructionsMd: string | null;
  durationMinutes: number | null;
  passScorePct: number;
  maxAttempts: number | null;
  dueAt: ISODate | null;
  proctoringConfig: {
    enabled: boolean;
    requireFaceMatch: boolean;
    requireFullscreen: boolean;
    maxRiskScore: number;
  };
  itemCount: number;
  totalPoints: number;
}

export interface SubmissionAnswer {
  id: ID;
  itemId: ID;
  responseData: unknown;
  gradingStatus: AnswerGradingStatus;
  autoScore: number | null;
  manualScore: number | null;
  finalScore: number | null;
  isCorrect: boolean | null;
  feedbackMd: string | null;
  aiSuggestion?: { score: number; feedbackMd: string; rubricScores: Record<string, number> } | null;
  gradedBy: { id: ID; fullName: string } | null;
  gradedAt: ISODate | null;
}

export interface Citation {
  kind: 'VIDEO' | 'DOCUMENT' | 'FAQ';
  label: string;
  sessionId?: ID;
  startSec?: number;
  endSec?: number;
  attachmentId?: ID;
  page?: number;
  snippet: string;
}

export interface ChatSession {
  publicId: string;
  scope: ChatScope;
  cohortId: ID | null;
  sessionId: ID | null;
  title: string | null;
  updatedAt: ISODate;
}

export interface ChatMessage {
  id: ID;
  role: 'user' | 'assistant';
  content: string;
  citations: Citation[];
  createdAt: ISODate;
}
